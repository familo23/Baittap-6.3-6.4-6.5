CREATE DATABASE IF NOT EXISTS GarageDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE GarageDB;

CREATE TABLE IF NOT EXISTS KhachHang (
	MaKH INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
	TenKH NVARCHAR(100) NOT NULL,
	DienThoai VARCHAR(15) NULL UNIQUE,
	DiaChi NVARCHAR(200) NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Xe (
	BienSo VARCHAR(20) NOT NULL PRIMARY KEY,
	MaKH INT NOT NULL,
	HieuXe NVARCHAR(50) NULL,
	NamSanXuat INT NULL,
	CONSTRAINT FK_Xe_KhachHang FOREIGN KEY (MaKH) REFERENCES KhachHang(MaKH)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS PhuTung (
	MaPhuTung INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
	TenPhuTung NVARCHAR(150) NOT NULL,
	DonGia DECIMAL(18,2) NOT NULL DEFAULT 0,
	SoLuongTon INT NOT NULL DEFAULT 0,
	CONSTRAINT CK_PhuTung_DonGia CHECK (DonGia >= 0),
	CONSTRAINT CK_PhuTung_SoLuongTon CHECK (SoLuongTon >= 0)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS PhieuSuaChua (
	MaPhieu INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
	BienSo VARCHAR(20) NOT NULL,
	NgayNhan DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	NoiDungSua LONGTEXT NULL,
	TongTien DECIMAL(18,2) NOT NULL DEFAULT 0,
	TrangThai NVARCHAR(30) NOT NULL DEFAULT 'Đang sửa',
	CONSTRAINT FK_PhieuSuaChua_Xe FOREIGN KEY (BienSo) REFERENCES Xe(BienSo)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ChiTietSuaChua (
	MaPhieu INT NOT NULL,
	MaPhuTung INT NOT NULL,
	SoLuong INT NOT NULL,
	TienCong DECIMAL(18,2) NOT NULL DEFAULT 0,
	PRIMARY KEY (MaPhieu, MaPhuTung),
	CONSTRAINT CK_ChiTietSuaChua_SoLuong CHECK (SoLuong > 0),
	CONSTRAINT CK_ChiTietSuaChua_TienCong CHECK (TienCong >= 0),
	CONSTRAINT FK_ChiTietSuaChua_Phieu FOREIGN KEY (MaPhieu) REFERENCES PhieuSuaChua(MaPhieu),
	CONSTRAINT FK_ChiTietSuaChua_PhuTung FOREIGN KEY (MaPhuTung) REFERENCES PhuTung(MaPhuTung)
) ENGINE=InnoDB;
