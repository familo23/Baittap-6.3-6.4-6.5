CREATE DATABASE IF NOT EXISTS ProjectTaskDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ProjectTaskDB;

CREATE TABLE IF NOT EXISTS DuAn (
	MaDuAn INT PRIMARY KEY AUTO_INCREMENT,
	TenDuAn NVARCHAR(150) NOT NULL,
	NgayBatDau DATETIME NULL,
	NgayKetThuc DATETIME NULL,
	TrangThai NVARCHAR(50) NOT NULL DEFAULT 'Đang chạy'
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ThanhVien (
	MaThanhVien INT PRIMARY KEY AUTO_INCREMENT,
	HoTen NVARCHAR(100) NOT NULL,
	Email VARCHAR(100) NOT NULL UNIQUE,
	ChuyenMon NVARCHAR(100) NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS CongViec (
	MaTask INT PRIMARY KEY AUTO_INCREMENT,
	MaDuAn INT NOT NULL,
	TenTask NVARCHAR(200) NOT NULL,
	MoTa NVARCHAR(1000) NULL,
	HanNop DATETIME NULL,
	DoUuTien NVARCHAR(20) NOT NULL DEFAULT 'Trung bình',
	TrangThai NVARCHAR(50) NOT NULL DEFAULT 'To Do',
	CONSTRAINT FK_CongViec_DuAn FOREIGN KEY (MaDuAn) REFERENCES DuAn(MaDuAn) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS PhanCong (
	MaTask INT NOT NULL,
	MaThanhVien INT NOT NULL,
	NgayGiao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (MaTask, MaThanhVien),
	CONSTRAINT FK_PhanCong_Task FOREIGN KEY (MaTask) REFERENCES CongViec(MaTask) ON DELETE CASCADE,
	CONSTRAINT FK_PhanCong_Member FOREIGN KEY (MaThanhVien) REFERENCES ThanhVien(MaThanhVien) ON DELETE CASCADE
) ENGINE=InnoDB;

